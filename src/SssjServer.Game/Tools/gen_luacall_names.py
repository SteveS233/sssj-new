#!/usr/bin/env python3
"""Generate src/SssjServer.Game/LuaCallNames.g.cs from docs/luacall-table.json.

Deterministic, committed source: each LuaCall id -> (name, chineseComment).
Run from repo root:  python3 server/src/SssjServer.Game/Tools/gen_luacall_names.py
Output overwrites server/src/SssjServer.Game/LuaCallNames.g.cs.
"""
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
TABLE = os.path.join(REPO, "docs", "luacall-table.json")
OUT = os.path.join(os.path.dirname(__file__), "..", "LuaCallNames.g.cs")

def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n")

def main() -> int:
    with open(TABLE, encoding="utf-8") as f:
        doc = json.load(f)
    cmds = doc["commands"]
    items = sorted((int(k), v) for k, v in cmds.items())

    lines = [
        "// <auto-generated> 由 server/src/SssjServer.Game/Tools/gen_luacall_names.py 生成，勿手改。",
        "// 数据源：docs/luacall-table.json（354 个 LuaCall 命令 id → 名称 + 中文注释）。",
        "// 重新生成：python3 server/src/SssjServer.Game/Tools/gen_luacall_names.py",
        "// 仅作用域到 Game 程序集（internal），供未处理命令日志使用。",
        "#nullable enable",
        "namespace SssjServer.Game;",
        "",
        "internal static partial class LuaCallNames",
        "{",
        f"    private static readonly System.Collections.Generic.Dictionary<int, (string Name, string Comment)> _map = new()",
        "    {",
    ]
    for cid, v in items:
        name = v.get("name", "")
        comment = v.get("comment", "")
        lines.append(f"        [{cid}] = (\"{esc(name)}\", \"{esc(comment)}\"),")
    lines += [
        "    };",
        "}",
        "",
    ]
    out = "\n".join(lines)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {OUT} ({len(items)} entries)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
