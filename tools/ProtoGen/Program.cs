using System.Text;
using System.Text.Json;

namespace SssjServer.ProtoGen;

public static class Program
{
    public static int Main(string[] args)
    {
        string GetOpt(string name, string def)
        {
            for (int i = 0; i + 1 < args.Length; i++)
                if (args[i] == name) return args[i + 1];
            return def;
        }

        string Resolve(string path)
        {
            if (Path.IsPathRooted(path)) return path;
            if (path.Contains('/') || path.Contains('\\')) return Path.GetFullPath(path);
            return Path.GetFullPath(Path.Combine(FindRepoRoot(), path));
        }

        string FindRepoRoot()
        {
            var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
            while (dir != null)
            {
                if (File.Exists(Path.Combine(dir.FullName, "docs", "proto-schema.json"))) return dir.FullName;
                dir = dir.Parent;
            }
            return Directory.GetCurrentDirectory();
        }

        var schemaPath = Resolve(GetOpt("--schema", "docs/proto-schema.json"));
        var pfPath = Resolve(GetOpt("--pf", "docs/pf-table.json"));
        var outArg = GetOpt("--out", "");
        var outDir = Path.IsPathRooted(outArg) || outArg.Contains("..")
            ? Path.GetFullPath(outArg)
            : Path.GetFullPath(Path.Combine(FindRepoRoot(), string.IsNullOrEmpty(outArg) ? "server/src/SssjServer.Protocol/Generated" : outArg));

        Console.WriteLine($"schema = {schemaPath}");
        Console.WriteLine($"pf     = {pfPath}");
        Console.WriteLine($"out    = {outDir}");

        var proto = JsonSerializer.Deserialize<ProtoRoot>(File.ReadAllText(schemaPath))
                    ?? throw new InvalidOperationException("bad proto-schema.json");
        var pfTable = JsonSerializer.Deserialize<PfRoot>(File.ReadAllText(pfPath))
                      ?? throw new InvalidOperationException("bad pf-table.json");

        // Fully clear the output directory first so a schema/naming change can never leave
        // orphaned files behind (the class set is derived entirely from the schema).
        if (Directory.Exists(outDir))
            ClearDirectory(new DirectoryInfo(outDir));
        Directory.CreateDirectory(outDir);

        int totalFields = 0;
        var generated = new List<(string csNs, string name, int fields)>();
        int fileCount = 0;
        foreach (var kv in proto.classes.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            var cls = kv.Value;
            var fields = cls.fields.OrderBy(f => f.number).ToList();
            totalFields += fields.Count;
            string csNs = cls.csharp_namespace;
            string csName = cls.csharp_name;

            int optionalIdx = 0;
            var models = new List<FieldModel>();
            var usedProp = new HashSet<string>(StringComparer.Ordinal);
            foreach (var f in fields)
            {
                bool repeated = f.repeated;
                bool isMsg = f.type_csharp is not null;
                Enc enc = isMsg ? Enc.Message : ReconcileEnc(EncOf(f.type), PrimitiveClr(f.csharp_type));

                // property CLR type + element CLR type
                string element, property;
                if (isMsg)
                {
                    element = f.type_csharp!;                        // fully-qualified element type, verbatim
                    property = repeated ? $"List<{element}>" : element;
                }
                else
                {
                    property = f.csharp_type;                       // already scalar or List<X> verbatim
                    element = repeated ? ElementOf(f.csharp_type) : f.csharp_type;
                }

                string prop = PascalCase(f.name);
                string baseProp = prop;
                int s = 2;
                while (!usedProp.Add(prop))
                    prop = baseProp + "_" + s++;

                int? hasBit = repeated ? null : optionalIdx++;
                models.Add(new FieldModel(f, enc, element, property, prop, repeated, hasBit));
            }

            int hasWords = (optionalIdx + 31) / 32;
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> 由 server/tools/ProtoGen 从 docs/proto-schema.json 生成，勿手改。");
            sb.AppendLine("#nullable enable");
            sb.AppendLine($"namespace {csNs};");
            sb.AppendLine();
            sb.AppendLine($"/// <summary>{cls.type_path} — Serialize RVA {cls.serialize_rva}</summary>");
            sb.AppendLine($"public sealed class {csName} : ProtoMessage");
            sb.AppendLine("{");
            for (int w = 0; w < hasWords; w++)
                sb.AppendLine($"    private uint _has{w};                       // 每 32 个 optional 字段一个 has 位图");
            foreach (var fm in models)
            {
                if (fm.Repeated)
                {
                    sb.AppendLine($"    /// <summary>field {fm.Number}, {fm.Field.type}, il2cpp offset 0x{fm.Offset:x}（原字段名 {fm.OrigName}）</summary>");
                    sb.AppendLine($"    public {fm.Property} {fm.Prop} {{ get; }} = new();   // repeated：只读属性，无 has 位");
                    sb.AppendLine();
                }
                else
                {
                    bool nullableRef = fm.Enc == Enc.Message;
                    string storage = fm.Enc == Enc.Message ? fm.ElementClr + "?" : fm.ElementClr;
                    string def = fm.Enc == Enc.Message ? "null" : DefaultValue(fm.Enc);
                    string bit = Bit(fm.HasBit!.Value);
                    string ww = (fm.HasBit.Value / 32).ToString();
                    sb.AppendLine($"    /// <summary>field {fm.Number}, {fm.Field.type}, il2cpp offset 0x{fm.Offset:x}（原字段名 {fm.OrigName}）</summary>");
                    sb.AppendLine($"    private {storage} _{fm.Prop} = {def};");
                    sb.AppendLine($"    public {storage} {fm.Prop} {{ get => _{fm.Prop}; set {{ _{fm.Prop} = value; _has{ww} |= {bit}; }} }}");
                    sb.AppendLine($"    public bool Has{fm.Prop} => (_has{ww} & {bit}) != 0;");
                    sb.AppendLine($"    public void Clear{fm.Prop}() {{ _{fm.Prop} = {def}; _has{ww} &= ~{bit}; }}");
                    sb.AppendLine();
                }
            }

            sb.AppendLine("    public override void WriteTo(ref ProtoWriter w)");
            sb.AppendLine("    {");
            foreach (var fm in models.OrderBy(m => m.Number))
            {
                string tag = $"w.WriteTag({fm.Number}, WireType.{WireName(fm.Enc)})";
                if (fm.Repeated)
                {
                    sb.AppendLine($"        foreach (var e in {fm.Prop})");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            {tag};");
                    sb.AppendLine($"            {WriteCall(fm.Enc)}(e);");
                    sb.AppendLine("        }");
                }
                else
                {
                    string bit = Bit(fm.HasBit!.Value);
                    string ww = (fm.HasBit.Value / 32).ToString();
                    sb.AppendLine($"        if ((_has{ww} & {bit}) != 0)");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            {tag};");
                    sb.AppendLine($"            {WriteCall(fm.Enc)}(_{fm.Prop}{(fm.Enc == Enc.Message ? "!" : "")});");
                    sb.AppendLine("        }");
                }
            }
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine("    public override void MergeFrom(ref ProtoReader r)");
            sb.AppendLine("    {");
            sb.AppendLine("        while (r.ReadTag(out var n, out var t))");
            sb.AppendLine("        {");
            sb.AppendLine("            switch (n)");
            sb.AppendLine("            {");
            foreach (var fm in models.OrderBy(m => m.Number))
            {
                sb.AppendLine($"                case {fm.Number}:");
                if (fm.Repeated)
                {
                    if (fm.Enc == Enc.Message)
                    {
                        sb.AppendLine("                {");
                        sb.AppendLine($"                    var e_{fm.Number} = new {fm.ElementClr}();");
                        sb.AppendLine($"                    r.ReadMessage(e_{fm.Number});");
                        sb.AppendLine($"                    {fm.Prop}.Add(e_{fm.Number});");
                        sb.AppendLine("                    break;");
                        sb.AppendLine("                }");
                    }
                    else
                    {
                        sb.AppendLine($"                    {fm.Prop}.Add({ReadExpr(fm.Enc)});");
                        sb.AppendLine("                    break;");
                    }
                }
                else
                {
                    string bit = Bit(fm.HasBit!.Value);
                    string ww = (fm.HasBit.Value / 32).ToString();
                    if (fm.Enc == Enc.Message)
                    {
                        sb.AppendLine("                {");
                        sb.AppendLine($"                    if (_{fm.Prop} is null) _{fm.Prop} = new {fm.ElementClr}();");
                        sb.AppendLine($"                    r.ReadMessage(_{fm.Prop});");
                        sb.AppendLine($"                    _has{ww} |= {bit};");
                        sb.AppendLine("                    break;");
                        sb.AppendLine("                }");
                    }
                    else
                    {
                        sb.AppendLine($"                    _{fm.Prop} = {ReadExpr(fm.Enc)};");
                        sb.AppendLine($"                    _has{ww} |= {bit};");
                        sb.AppendLine("                    break;");
                    }
                }
            }
            sb.AppendLine("                default:");
            sb.AppendLine("                    r.SkipField(t);");
            sb.AppendLine("                    break;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();

            sb.AppendLine("    public override int ComputeSize()");
            sb.AppendLine("    {");
            sb.AppendLine("        int size = 0;");
            foreach (var fm in models.OrderBy(m => m.Number))
            {
                if (fm.Repeated)
                {
                    sb.AppendLine($"        foreach (var e in {fm.Prop})");
                    sb.AppendLine($"            size += SizeOf.Tag({fm.Number}) + {SizeExpr(fm.Enc, "e")};");
                }
                else
                {
                    string bit = Bit(fm.HasBit!.Value);
                    string ww = (fm.HasBit.Value / 32).ToString();
                    sb.AppendLine($"        if ((_has{ww} & {bit}) != 0)");
                    sb.AppendLine($"            size += SizeOf.Tag({fm.Number}) + {SizeExpr(fm.Enc, $"_{fm.Prop}{(fm.Enc == Enc.Message ? "!" : "")}")};");
                }
            }
            sb.AppendLine("        return size;");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            string file = Path.Combine(outDir, kv.Key.Replace('.', '_') + ".cs");
            File.WriteAllText(file, sb.ToString(), new UTF8Encoding(false));
            fileCount++;
            generated.Add((csNs, csName, fields.Count));
        }

        // ---------------- Pf.cs ----------------
        // Build schema key -> csharp type from the self-describing classes
        var clsTypeByKey = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var kv in proto.classes)
            clsTypeByKey[kv.Key] = kv.Value.csharp_namespace + "." + kv.Value.csharp_name;

        var pfEntries = pfTable.pf.Values.OrderBy(p => p.pf).ToList();
        var names = new Dictionary<int, string>();
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var e in pfEntries)
        {
            string name = PfNameFor(e);
            if (!used.Add(name))
                name = name + "_" + e.pf;
            used.Add(name);
            names[e.pf] = name;
        }

        var pfb = new StringBuilder();
        pfb.AppendLine("// <auto-generated> 由 server/tools/ProtoGen 从 docs/pf-table.json 生成，勿手改。");
        pfb.AppendLine("#nullable enable");
        pfb.AppendLine("namespace SssjServer.Protocol;");
        pfb.AppendLine();
        pfb.AppendLine("/// <summary>pf 常量表：pf → 消息类型 / 调用方。</summary>");
        pfb.AppendLine("public static class Pf");
        pfb.AppendLine("{");
        foreach (var e in pfEntries)
        {
            string n = names[e.pf];
            string doc;
            if (!string.IsNullOrEmpty(e.message))
                doc = $"pf {e.pf} — {e.message}";
            else
            {
                var callers = e.send.Concat(e.register).Where(s => !string.IsNullOrEmpty(s)).ToList();
                doc = $"pf {e.pf} — 调用方: {(callers.Count == 0 ? "无" : string.Join(", ", callers))}";
            }
            pfb.AppendLine($"    /// <summary>{doc}</summary>");
            pfb.AppendLine($"    public const int {n} = {e.pf};");
            pfb.AppendLine();
        }
        pfb.AppendLine("    private static readonly System.Collections.Generic.Dictionary<int, System.Type> _registry = new()");
        pfb.AppendLine("    {");
        foreach (var e in pfEntries.Where(x => !string.IsNullOrEmpty(x.message)).OrderBy(x => x.pf))
        {
            if (!clsTypeByKey.TryGetValue(e.message!, out var t))
                throw new InvalidOperationException($"pf {e.pf}: schema key '{e.message}' not found in proto-schema.json");
            pfb.AppendLine($"        [{e.pf}] = typeof({t}),");
        }
        pfb.AppendLine("    };");
        pfb.AppendLine();
        pfb.AppendLine("    /// <summary>pf → 消息 CLR 类型（仅 message 非空的 pf）。</summary>");
        pfb.AppendLine("    public static IReadOnlyDictionary<int, Type> Registry { get; } = _registry;");
        pfb.AppendLine();
        pfb.AppendLine("    /// <summary>返回该 pf 注册的 CLR 类型名，未注册返回 \"pf=&lt;编号&gt;\"（日志用）。</summary>");
        pfb.AppendLine("    public static string Name(int pf)");
        pfb.AppendLine("    {");
        pfb.AppendLine("        if (_registry.TryGetValue(pf, out var t)) return t.Name;");
        pfb.AppendLine("        foreach (var e in _aliases)");
        pfb.AppendLine("            if (e.pf == pf) return e.name;");
        pfb.AppendLine("        return \"pf=\" + pf;");
        pfb.AppendLine("    }");
        pfb.AppendLine();
        pfb.AppendLine("    private static readonly (int pf, string name)[] _aliases =");
        pfb.AppendLine("    {");
        foreach (var e in pfEntries)
            pfb.AppendLine($"        ({e.pf}, nameof({names[e.pf]})),");
        pfb.AppendLine("    };");
        pfb.AppendLine("}");
        pfb.AppendLine();

        File.WriteAllText(Path.Combine(outDir, "Pf.cs"), pfb.ToString(), new UTF8Encoding(false));

        Console.WriteLine();
        Console.WriteLine($"Generated {generated.Count} message classes ({fileCount} files), {totalFields} fields, in {outDir}");
        Console.WriteLine($"Generated Pf.cs with {pfEntries.Count} pf constants, {pfEntries.Count(x => !string.IsNullOrEmpty(x.message))} registry entries.");
        return 0;
    }

    // ------------------------------------------------------------
    /// <summary>Recursively delete all files and subdirectories under a directory.</summary>
    private static void ClearDirectory(DirectoryInfo dir)
    {
        foreach (var sub in dir.GetDirectories())
            ClearDirectory(sub);
        foreach (var f in dir.GetFiles())
            f.Delete();
        dir.Delete();
    }

    private static string ElementOf(string listType)
        => listType.StartsWith("List<", StringComparison.Ordinal) && listType.EndsWith(">")
            ? listType.Substring(5, listType.Length - 6)
            : listType;

    private static bool IsPrimitive(string type) => type switch
    {
        "int32" or "uint32" or "int64" or "uint64" or "sint32" or "sint64" or
        "fixed32" or "sfixed32" or "fixed64" or "sfixed64" or
        "float" or "double" or "string" or "bytes" or "bool" => true,
        _ => false
    };

    private enum Enc { Int32, UInt32, Int64, UInt64, SInt32, SInt64, Bool, Fixed32, SFixed32, Fixed64, SFixed64, Float, Double, Str, Bytes, Message }

    private static Enc EncOf(string type) => type switch
    {
        "int32" => Enc.Int32,
        "uint32" => Enc.UInt32,
        "int64" => Enc.Int64,
        "uint64" => Enc.UInt64,
        "sint32" => Enc.SInt32,
        "sint64" => Enc.SInt64,
        "bool" => Enc.Bool,
        "fixed32" => Enc.Fixed32,
        "sfixed32" => Enc.SFixed32,
        "fixed64" => Enc.Fixed64,
        "sfixed64" => Enc.SFixed64,
        "float" => Enc.Float,
        "double" => Enc.Double,
        "string" => Enc.Str,
        "bytes" => Enc.Bytes,
        _ => Enc.Message
    };

    /// <summary>调解 schema 里 type（编码）与 csharp_type（CLR 类型）的矛盾（仅 PvpNormalAchieve 两个伪重复行）。</summary>
    private static Enc ReconcileEnc(Enc e, string clr)
    {
        if (clr is "float") return Enc.Float;
        if (clr is "double") return Enc.Double;
        if (e is Enc.Float or Enc.Double)
        {
            return clr switch
            {
                "int" => Enc.Int32,
                "uint" => Enc.UInt32,
                "long" => Enc.Int64,
                "ulong" => Enc.UInt64,
                _ => e
            };
        }
        return e;
    }

    private static string WireName(Enc e) => e switch
    {
        Enc.Fixed32 or Enc.SFixed32 or Enc.Float => "Fixed32",
        Enc.Fixed64 or Enc.SFixed64 or Enc.Double => "Fixed64",
        Enc.Message or Enc.Str or Enc.Bytes => "Length",
        _ => "Varint"
    };

    private static string SizeExpr(Enc e, string v) => e switch
    {
        Enc.Int32 => $"SizeOf.Int32({v})",
        Enc.UInt32 => $"SizeOf.UInt32({v})",
        Enc.Int64 => $"SizeOf.Int64({v})",
        Enc.UInt64 => $"SizeOf.UInt64({v})",
        Enc.SInt32 => $"SizeOf.SInt32({v})",
        Enc.SInt64 => $"SizeOf.SInt64({v})",
        Enc.Bool => "1",
        Enc.Fixed32 or Enc.SFixed32 or Enc.Float => "SizeOf.Fixed32",
        Enc.Fixed64 or Enc.SFixed64 or Enc.Double => "SizeOf.Fixed64",
        Enc.Str => $"SizeOf.String({v})",
        Enc.Bytes => $"SizeOf.Bytes({v})",
        Enc.Message => $"SizeOf.Message({v})",
        _ => throw new InvalidOperationException()
    };

    private static string ReadExpr(Enc e) => e switch
    {
        Enc.Int32 => "r.ReadInt32()",
        Enc.UInt32 => "r.ReadUInt32()",
        Enc.Int64 => "r.ReadInt64()",
        Enc.UInt64 => "r.ReadUInt64()",
        Enc.SInt32 => "r.ReadSInt32()",
        Enc.SInt64 => "r.ReadSInt64()",
        Enc.Bool => "r.ReadBool()",
        Enc.Fixed32 => "r.ReadFixed32()",
        Enc.SFixed32 => "r.ReadSFixed32()",
        Enc.Fixed64 => "r.ReadFixed64()",
        Enc.SFixed64 => "r.ReadSFixed64()",
        Enc.Float => "r.ReadFloat()",
        Enc.Double => "r.ReadDouble()",
        Enc.Str => "r.ReadString()",
        Enc.Bytes => "r.ReadBytes()",
        _ => throw new InvalidOperationException()
    };

    private static string WriteCall(Enc e) => e switch
    {
        Enc.Int32 => "w.WriteInt32",
        Enc.UInt32 => "w.WriteUInt32",
        Enc.Int64 => "w.WriteInt64",
        Enc.UInt64 => "w.WriteUInt64",
        Enc.SInt32 => "w.WriteSInt32",
        Enc.SInt64 => "w.WriteSInt64",
        Enc.Bool => "w.WriteBool",
        Enc.Fixed32 => "w.WriteFixed32",
        Enc.SFixed32 => "w.WriteSFixed32",
        Enc.Fixed64 => "w.WriteFixed64",
        Enc.SFixed64 => "w.WriteSFixed64",
        Enc.Float => "w.WriteFloat",
        Enc.Double => "w.WriteDouble",
        Enc.Str => "w.WriteString",
        Enc.Bytes => "w.WriteBytes",
        Enc.Message => "w.WriteMessage",
        _ => throw new InvalidOperationException()
    };

    private static string DefaultValue(Enc e) => e switch
    {
        Enc.Str => "\"\"",
        Enc.Bytes => "Array.Empty<byte>()",
        Enc.Bool => "false",
        Enc.Message => "null",
        _ => "0"
    };

    private static string Bit(int i) => $"0x{(1u << i):x}u";

    private static string PrimitiveClr(string csharp_type) => csharp_type switch
    {
        "string" => "string",
        "byte[]" => "byte[]",
        "bool" => "bool",
        "float" => "float",
        "double" => "double",
        "int" => "int",
        "uint" => "uint",
        "long" => "long",
        "ulong" => "ulong",
        _ => csharp_type
    };

    private static string PascalCase(string name)
    {
        var sb = new StringBuilder();
        foreach (var seg in name.Split('_'))
        {
            if (seg.Length == 0) continue;
            sb.Append(char.ToUpperInvariant(seg[0]));
            if (seg.Length > 1) sb.Append(seg.Substring(1));
        }
        if (sb.Length == 0)
            return name.StartsWith('_') ? name : "_" + name;
        if (char.IsDigit(sb[0]))
            sb.Insert(0, '_');
        return sb.ToString();
    }

    private static string PfNameFor(PfEntry e)
    {
        if (e.pf == 1001) return "Login"; // canonical name from the interface contract (§2 of 02-server-design.md)
        if (!string.IsNullOrEmpty(e.message))
            return SanitizeIdent(e.message.Substring(e.message.LastIndexOf('.') + 1));
        string derived = DeriveFromCallers(e.send);
        if (derived.Length == 0) derived = DeriveFromCallers(e.register);
        if (derived.Length == 0) derived = $"Pf{e.pf}";
        return derived;
    }

    private static string DeriveFromCallers(List<string> callers)
    {
        foreach (var c in callers)
        {
            if (string.IsNullOrEmpty(c)) continue;
            int sep = c.LastIndexOf("$$");
            string seg = sep >= 0 ? c.Substring(sep + 2) : c;
            seg = SanitizeIdent(seg);
            if (seg.Length > 0) return seg;
        }
        return "";
    }

    private static string SanitizeIdent(string s)
    {
        var sb = new StringBuilder();
        foreach (var ch in s)
        {
            if (char.IsLetterOrDigit(ch) || ch == '_') sb.Append(ch);
        }
        if (sb.Length == 0) return "";
        if (char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

    private sealed record FieldModel(Field Field, Enc Enc, string ElementClr, string Property, string Prop, bool Repeated, int? HasBit)
    {
        public int Number => Field.number;
        public int Offset => Field.offset;
        public string OrigName => Field.name;
    }
}

public record ProtoRoot(Dictionary<string, Class> classes);
public record Class(string name, string type_path, string @namespace, string csharp_namespace, string csharp_name, string serialize_rva, List<Field> fields);
public record Field(string name, string csharp_type, int offset, int number, int wire, string type, bool repeated, string? type_ref, string? type_csharp);
public record PfRoot(Dictionary<string, PfEntry> pf);
public record PfEntry(int pf, List<string> send, List<string> register, string? message);
